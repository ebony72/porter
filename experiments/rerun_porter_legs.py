"""Re-run the PORTER legs of paper/compare_results.json under the new protocol.

PORTER's routing protocol became density-adaptive best-of-3 lookahead-horizon
selection (`compile_porter.route` / `run_horizon_selection`) on 2026-08-29, so
every leg in which PORTER routes has to be recomputed.  Legs that do not depend
on PORTER's router -- dSABRE's own protocol, TeleSABRE, pytket-dqc's ebit count,
and `dSE_on_porter_layout` (which consumes PORTER's *layout*, unchanged) -- are
independent of the change and are carried over untouched, the same discipline
`rerun_telesabre_legs.py` used.

Only the SINGLE-PASS PORTER legs change.  Refinement and the gamma search
keep their own unselected horizon on purpose (see
`compile_porter.run_refinement_passes`), so `sfc_refined`, `sfc_search` and
every `*_refined` leg keep their published numbers.  This script covers the
two single-pass legs reachable without re-running an external baseline:

    sfc                    PORTER's own layout
    sfc_on_dse_layout      PORTER on dSABRE's SabreLayout candidates

`sfc_shared` and `sfc_pytket` need TeleSABRE's and pytket-dqc's layouts, which
are not stored in the results file; they must be regenerated by a full
`compare_routers.py` run.

Writes paper/compare_results_selection.json -- NOT compare_results.json, so the
released file is never left half-converted.

Sections:

    main       paper/compare_results.json   -> compare_results_selection.json
    scaleup    paper/scaleup_results.json   -> scaleup_results_selection.json
    heavyhex   paper/heavyhex_results.json  -> heavyhex_results_selection.json

    python rerun_porter_legs.py                   # every section
    python rerun_porter_legs.py main 25 64        # main suite, named suites
    python rerun_porter_legs.py scaleup heavyhex
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent   # repo root
sys.path.insert(0, str(_ROOT))

import compare_routers as cr
import compile_porter as cdr

RESULTS = _ROOT / "paper" / "compare_results.json"
OUT = _ROOT / "paper" / "compare_results_selection.json"
# Only the SINGLE-PASS PORTER legs change: horizon selection is PORTER's
# routing protocol, but refinement and the gamma search deliberately keep
# their own (unselected) horizon -- see run_refinement_passes -- so
# sfc_refined, sfc_search and every *_refined leg keep their published
# numbers and are not recomputed here.
PORTER_LEGS = ("sfc", "sfc_on_dse_layout", "sfc_selection_and_search")


def section_scaleup() -> None:
    """Scale-up: only `sfc` and `sfc_on_dse_layout` change."""
    import bench_scaleup as bs
    out = _ROOT / "paper" / "scaleup_results_selection.json"
    rows = json.loads((_ROOT / "paper" / "scaleup_results.json").read_text())
    for row in rows:
        spec = bs.SUITES[row["suite"]]
        _, hw = cdr.hardware_from_device_json(
            _ROOT.parent / "other" / "telesabre" / "devices" / f"{spec['device']}.json")
        fname = next(f for f in spec["files"] if f.startswith(row["circuit"] + "_"))
        qasm = spec["circuit_dir"] / fname
        circuit, num_logical = cdr.parse_qasm2(qasm)
        qc, dag = cr.load_qasm(qasm)
        arch = cr.sfc_hardware_to_dsabre_architecture(hw)
        cr.verify_topology_match(hw, arch)
        layouts = cr.dsabre_layout_candidates(qc, dag, arch, seed=0)
        t0 = time.perf_counter()
        row["sfc"] = cr.run_sfc(circuit, hw, num_logical)
        row["sfc_on_dse_layout"] = cr.run_sfc_sabre_layout(
            circuit, hw, num_logical, dag, layouts)
        row["sfc_selection_and_search"] = cr.run_sfc_selection_and_search(
            circuit, hw, num_logical)
        g = lambda k: (row.get(k) or {}).get("epr")
        print(f"[{row['suite']}q {row['circuit']}] sfc={g('sfc')} "
              f"(L={(row.get('sfc') or {}).get('chosen_horizon')}) "
              f"onDSE={g('sfc_on_dse_layout')} | dSE={g('dSE')} "
              f"+R={g('sfc_refined')} (unchanged)  [{time.perf_counter()-t0:.0f}s]", flush=True)
        out.write_text(json.dumps(rows, indent=2))
    out.write_text(json.dumps(rows, indent=2))
    print(f"\nwrote {out}", flush=True)


def section_heavyhex() -> None:
    """Heavy-hex: only `porter` and `porter_on_dse` change."""
    import compare_heavyhex as ch
    out = _ROOT / "paper" / "heavyhex_results_selection.json"
    rows = json.loads((_ROOT / "paper" / "heavyhex_results.json").read_text())
    hw_by_topo = {}
    for row in rows:
        topo = row["topology"]
        if topo not in hw_by_topo:
            arch = ch.build_heavy_hex_architecture(ch.NUM_CORES, topo)
            hw = ch.dsabre_architecture_to_porter_hardware(arch)
            cr.verify_topology_match(hw, arch)
            hw_by_topo[topo] = (arch, hw)
        arch, hw = hw_by_topo[topo]
        cname = row["circuit"]
        qf = ch.CIRCUIT_DIR / (ch.QNN_FILE if cname == "qnn" else cname + ch.SUFFIX)
        circuit, num_logical = cdr.parse_qasm2(qf)
        qc, dag = cr.load_qasm(qf)
        layouts = ch.sabre_locked_boundary_layout(qc, dag, arch, seed=0)
        t0 = time.perf_counter()
        cfg = cr.dr.RouterConfig(random_seed=0)
        try:
            layout = cdr.build_initial_layout(
                circuit, hw, num_logical,
                min_free_per_core=cfg.min_free_before_teleport)
            state, sel = cdr.route(hw, cfg, circuit, layout,
                                   pass_guard=cr._compiler_time_limit)
            row["porter"] = dict(epr=state.stats.epr,
                                 swaps=state.stats.local_swap_count,
                                 teleports=state.stats.teleport_count,
                                 telegates=state.stats.telegate_count,
                                 packets=state.stats.telegate_packet_count,
                                 depth=state.stats.depth,
                                 chosen_horizon=sel.get("chosen_horizon"),
                                 seconds=round(time.perf_counter() - t0, 3))
        except (RuntimeError, ValueError, cr.CompilerTimeout) as exc:
            row["porter"] = {"error": f"{type(exc).__name__}: {str(exc)[:140]}"}
        row["porter_on_dse"] = cr.run_sfc_sabre_layout(
            circuit, hw, num_logical, dag, layouts)
        g = lambda k: (row.get(k) or {}).get("epr")
        print(f"[{topo} {cname}] porter={g('porter')} "
              f"(L={(row.get('porter') or {}).get('chosen_horizon')}) "
              f"onDSE={g('porter_on_dse')} | dSE={g('dSE')} "
              f"+R={g('porter_refined')} (unchanged)  [{time.perf_counter()-t0:.0f}s]", flush=True)
        out.write_text(json.dumps(rows, indent=2))
    out.write_text(json.dumps(rows, indent=2))
    print(f"\nwrote {out}", flush=True)


def section_shared() -> None:
    """Shared-layout leg: PORTER routing TeleSABRE's own initial mapping.

    Reads the layouts cached by `harvest_shared_layouts.py` rather than
    re-invoking TeleSABRE -- its results are unaffected by a change to
    PORTER's router, so only its layouts are needed, and they are
    deterministic.  `sfc_shared_refined` does not select and is unchanged.
    """
    layouts = json.loads((_ROOT / "paper" / "shared_layouts.json").read_text())
    out = _ROOT / "paper" / "compare_results_selection.json"
    rows = json.loads(out.read_text())
    for row in rows:
        key = f"{row['suite']}_{row['circuit']}"
        entry = layouts.get(key)
        if not entry or not entry.get("phys_to_virt"):
            print(f"[{key}] no TeleSABRE layout -- leg stays None", flush=True)
            continue
        if not entry.get("reproduces"):
            print(f"[{key}] SKIPPED: harvested layout did not reproduce the "
                  f"recorded TeleSABRE result", flush=True)
            continue
        spec = cr.SUITES[row["suite"]]
        _, hw = cdr.hardware_for_name(spec["arch_name"])
        fname = next(f for f in spec["files"]
                     if f.split("_nativegates")[0].replace(".qasm", "") in
                     (row["circuit"], row["circuit"] + "_OLD_DEEP")
                     or f.startswith(row["circuit"] + "_"))
        circuit, num_logical = cdr.parse_qasm2(spec["circuit_dir"] / fname)
        t0 = time.perf_counter()
        old = (row.get("sfc_shared") or {}).get("epr")
        row["sfc_shared"] = cr.run_sfc_shared_layout(
            circuit, hw, num_logical, entry["phys_to_virt"])
        new = (row.get("sfc_shared") or {}).get("epr")
        print(f"[{key}] sfc_shared {old} -> {new} "
              f"(L={(row.get('sfc_shared') or {}).get('chosen_horizon')}) "
              f"| TS={(row.get('telesabre') or {}).get('epr')} "
              f"dSE_shared={(row.get('dSE_shared') or {}).get('epr')}  "
              f"[{time.perf_counter()-t0:.0f}s]", flush=True)
        out.write_text(json.dumps(rows, indent=2))
    out.write_text(json.dumps(rows, indent=2))
    print(f"\nwrote {out}", flush=True)


def section_pytket() -> None:
    """pytket-shared-layout leg, from the cached placements.

    Same reasoning as `section_shared`: PORTER's leg needs pytket-dqc's
    partition, not its ebit count, and the partitioner is deterministic.
    `sfc_pytket_refined` does not select and is unchanged.
    """
    cache = json.loads((_ROOT / "paper" / "pytket_placements.json").read_text())
    out = _ROOT / "paper" / "compare_results_selection.json"
    rows = json.loads(out.read_text())
    for row in rows:
        key = f"{row['suite']}_{row['circuit']}"
        entry = cache.get(key)
        if not entry or not entry.get("placement") or not entry.get("reproduces"):
            print(f"[{key}] no usable pytket placement -- leg unchanged", flush=True)
            continue
        spec = cr.SUITES[row["suite"]]
        _, hw = cdr.hardware_for_name(spec["arch_name"])
        fname = next(f for f in spec["files"]
                     if f.split("_nativegates")[0].replace(".qasm", "") in
                     (row["circuit"], row["circuit"] + "_OLD_DEEP")
                     or f.startswith(row["circuit"] + "_"))
        qasm = spec["circuit_dir"] / fname
        circuit, num_logical = cdr.parse_qasm2(qasm)
        _, dag = cr.load_qasm(qasm)
        arch = cr.sfc_hardware_to_dsabre_architecture(hw)
        placement = {int(k): v for k, v in entry["placement"].items()}
        corners = set(entry["corner_nodes"])
        t0 = time.perf_counter()
        old = (row.get("sfc_pytket") or {}).get("epr")
        try:
            row["sfc_pytket"] = cr.run_sfc_pytket_layout(
                circuit, hw, num_logical, dag, arch, placement, corners)
        except (RuntimeError, ValueError) as exc:
            print(f"[{key}] FAILED: {type(exc).__name__}: {str(exc)[:90]}", flush=True)
            continue
        new = (row.get("sfc_pytket") or {}).get("epr")
        print(f"[{key}] sfc_pytket {old} -> {new} "
              f"(L={(row.get('sfc_pytket') or {}).get('chosen_horizon')}) "
              f"| ebits={row.get('pytket_ebits')} "
              f"dSE_pytket={(row.get('dSE_pytket') or {}).get('epr')}  "
              f"[{time.perf_counter()-t0:.0f}s]", flush=True)
        out.write_text(json.dumps(rows, indent=2))
    out.write_text(json.dumps(rows, indent=2))
    print(f"\nwrote {out}", flush=True)


def main() -> None:
    args = list(sys.argv[1:])
    sections = [a for a in args if a in ("main", "scaleup", "heavyhex",
                                        "shared", "pytket")]
    if not sections:
        sections = ["main", "scaleup", "heavyhex"]
    if "pytket" in sections:
        section_pytket()
        if sections == ["pytket"]:
            return
    if "shared" in sections:
        section_shared()
        if sections == ["shared"]:
            return
    if "scaleup" in sections:
        section_scaleup()
    if "heavyhex" in sections:
        section_heavyhex()
    if "main" not in sections:
        return
    want = set(a for a in args if a in cr.SUITES) or set(cr.SUITES)
    # Read from OUT when it exists: other sections (shared, pytket) write
    # their legs there, and re-reading the RELEASED file would silently
    # revert them.  RESULTS is only the starting point for a fresh run.
    src = OUT if OUT.exists() else RESULTS
    rows = json.loads(src.read_text())
    done = {}
    if OUT.exists():
        done = {f"{r['suite']}_{r['circuit']}": r for r in json.loads(OUT.read_text())}

    for row in rows:
        key = f"{row['suite']}_{row['circuit']}"
        if row["suite"] not in want:
            continue
        if key in done and all(l in done[key] for l in PORTER_LEGS):
            row.update({l: done[key][l] for l in PORTER_LEGS})
            print(f"[{key}] cached", flush=True)
            continue

        spec = cr.SUITES[row["suite"]]
        _, hw = cdr.hardware_for_name(spec["arch_name"])
        fname = next(f for f in spec["files"]
                     if f.split("_nativegates")[0].replace(".qasm", "") in
                     (row["circuit"], row["circuit"] + "_OLD_DEEP")
                     or f.startswith(row["circuit"] + "_"))
        qasm = spec["circuit_dir"] / fname
        circuit, num_logical = cdr.parse_qasm2(qasm)
        qc, dag = cr.load_qasm(qasm)
        arch = cr.sfc_hardware_to_dsabre_architecture(hw)
        cr.verify_topology_match(hw, arch)
        layouts = cr.sabre_two_corner_layout(qc, dag, arch, seed=0)

        t0 = time.perf_counter()
        row["sfc"] = cr.run_sfc(circuit, hw, num_logical)
        row["sfc_on_dse_layout"] = cr.run_sfc_sabre_layout(
            circuit, hw, num_logical, dag, layouts)
        row["sfc_selection_and_search"] = cr.run_sfc_selection_and_search(
            circuit, hw, num_logical)
        g = lambda k: (row.get(k) or {}).get("epr")
        print(f"[{key}] sfc={g('sfc')} (L={(row.get('sfc') or {}).get('chosen_horizon')}) "
              f"onDSE={g('sfc_on_dse_layout')} (L={(row.get('sfc_on_dse_layout') or {}).get('chosen_horizon')}) "
              f"+SR={g('sfc_selection_and_search')} "
              f"({(row.get('sfc_selection_and_search') or {}).get('chosen_schedule')}) "
              f"| dSE={g('dSE')} +S={g('sfc_search')} (unchanged)  "
              f"[{time.perf_counter()-t0:.0f}s]", flush=True)
        OUT.write_text(json.dumps(rows, indent=2))

    OUT.write_text(json.dumps(rows, indent=2))
    print(f"\nwrote {OUT}", flush=True)


if __name__ == "__main__":
    main()
